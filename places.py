def nearest_town(lat, lon):
    best, bd = None, 1e9
    kx = math.cos(math.radians(lat))
    for t in TOWNS:
        d = (t[1] - lat) ** 2 + ((t[2] - lon) * kx) ** 2
        if d < bd:
            best, bd = t, d
    return [best[0], best[3], best[4]]
